DROP DATABASE sportscenter;

CREATE DATABASE sportscenter;

\c sportscenter

-- 종목 개설강좌 목록
DROP TABLE IF EXISTS sports;

CREATE TABLE sports
(
    sport_id    SERIAL      PRIMARY KEY,
    sport_name  VARCHAR(20) NOT NULL 
);

-- TABLE CREATION
DROP TABLE IF EXISTS members;

CREATE TABLE members
(
    member_id   SERIAL      PRIMARY KEY,
    name        VARCHAR(30) NOT NULL,
    gender      CHAR(1)     NOT NULL,
    birth_year  SMALLINT    NOT NULL,
    phone       VARCHAR(20),
    email       VARCHAR(50),
    region      VARCHAR(10),
    join_date   DATE        NOT NULL
);

-- 강사 테이블
DROP TABLE IF EXISTS instructors;

CREATE TABLE instructors
(
    instructor_id   SERIAL      PRIMARY KEY,
    name            VARCHAR(20) NOT NULL,
    sport_id       INT         NOT NULL REFERENCES sports (sport_id),
    phone           VARCHAR(20),
    hire_date       DATE        NOT NULL
);

-- 개설 강좌
DROP TABLE IF EXISTS courses;

CREATE TABLE courses
(
    course_id       SERIAL      PRIMARY KEY,
    sport_id       INT          NOT NULL REFERENCES sports (sport_id), -- 외래키 (Foregn Key)
    course_name     VARCHAR(30) NOT NULL,
    level           VARCHAR(10) NOT NULL,
    class_days      VARCHAR(10) NOT NULL,
    start_time      TIME        NOT NULL,
    capacity        SMALLINT    NOT NULL,
    fee             INT         NOT NULL,
    instructor_id   INT         REFERENCES instructors (instructor_id)
);

DROP TABLE IF EXISTS lockers;

-- 1:1 사물함 테이블
CREATE TABLE lockers
(
    locker_no   INT     PRIMARY KEY,
    member_id   INT     NOT NULL UNIQUE REFERENCES members (member_id) ON DELETE CASCADE,
    assign_date  DATE    NOT NULL
);

-- 수강 신청 테이블
DROP TABLE IF EXISTS enrollments;

CREATE TABLE enrollments
(
    member_id       INT             NOT NULL REFERENCES members (member_id),
    course_id       INT             NOT NULL REFERENCES courses (course_id),
    enroll_month    CHAR(7)         NOT NULL,
    status          VARCHAR(10)     NOT NULL,
    pay_amount      NUMERIC(10,2)   DEFAULT 0 CHECK (pay_amount >=0),
    PRIMARY KEY (member_id, course_id, enroll_month)
);


